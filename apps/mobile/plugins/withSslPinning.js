/**
 * SSL (public-key) pinning, applied at build time (`expo prebuild` / `expo run:*` / EAS).
 *
 * Android  network_security_config.xml with <pin-set> per domain.
 *          release: no cleartext HTTP at all. debug: cleartext allowed so Metro works.
 * iOS      Info.plist NSAppTransportSecurity → NSPinnedDomains (iOS 14+).
 *
 * React Native's networking (OkHttp on Android, URLSession on iOS) honours both,
 * so every API call is pinned without code changes.
 *
 * Options (app.json):
 *   domains: [{ host, pins: ["base64 SPKI SHA-256", …], includeSubdomains?, expiration? }]
 *   iosPinType: "ca" (pins are intermediate/root CA keys) | "leaf" (pins are the server key)
 * Always ship at least two pins per domain (current + backup key), or a certificate
 * renewal will lock every user out until they update the app.
 */
const fs = require("fs");
const path = require("path");
const { withAndroidManifest, withDangerousMod, withInfoPlist } = require("expo/config-plugins");

const FILE = "network_security_config";

const validDomains = (domains = []) =>
  domains.filter((d) => {
    const pins = (d && Array.isArray(d.pins) ? d.pins : []).filter((p) => p && !String(p).startsWith("REPLACE_"));
    if (d) d.pins = pins;
    const ok = d && d.host && pins.length >= 2;
    if (!ok) console.warn(`[withSslPinning] ${d && d.host}: needs at least 2 pins — pinning NOT applied for it.`);
    return ok;
  });

const xml = (domains, cleartext) => `<?xml version="1.0" encoding="utf-8"?>
<!-- generated by plugins/withSslPinning.js — edit app.json, not this file -->
<network-security-config>
  <base-config cleartextTrafficPermitted="${cleartext}">
    <trust-anchors><certificates src="system" /></trust-anchors>
  </base-config>
${domains
  .map(
    (d) => `  <domain-config cleartextTrafficPermitted="false">
    <domain includeSubdomains="${d.includeSubdomains !== false}">${d.host}</domain>
    <pin-set${d.expiration ? ` expiration="${d.expiration}"` : ""}>
${d.pins.map((p) => `      <pin digest="SHA-256">${p}</pin>`).join("\n")}
    </pin-set>
  </domain-config>`,
  )
  .join("\n")}
</network-security-config>
`;

const withAndroidPinning = (config, domains) => {
  config = withDangerousMod(config, [
    "android",
    (c) => {
      const appDir = path.join(c.modRequest.platformProjectRoot, "app", "src");
      for (const [buildType, cleartext] of [["debug", true], ["release", false]]) {
        const dir = path.join(appDir, buildType, "res", "xml");
        fs.mkdirSync(dir, { recursive: true });
        fs.writeFileSync(path.join(dir, `${FILE}.xml`), xml(domains, cleartext));
      }
      return c;
    },
  ]);
  return withAndroidManifest(config, (c) => {
    const app = c.modResults.manifest.application?.[0];
    if (app) app.$["android:networkSecurityConfig"] = `@xml/${FILE}`;
    return c;
  });
};

const withIosPinning = (config, domains, pinType) =>
  withInfoPlist(config, (c) => {
    const key = pinType === "leaf" ? "NSPinnedLeafIdentities" : "NSPinnedCAIdentities";
    const ats = c.modResults.NSAppTransportSecurity ?? {};
    ats.NSPinnedDomains = Object.fromEntries(
      domains.map((d) => [
        d.host,
        { NSIncludesSubdomains: d.includeSubdomains !== false, [key]: d.pins.map((p) => ({ "SPKI-SHA256-BASE64": p })) },
      ]),
    );
    c.modResults.NSAppTransportSecurity = ats;
    return c;
  });

module.exports = function withSslPinning(config, options = {}) {
  const domains = validDomains(options.domains);
  if (!domains.length) return config;
  config = withAndroidPinning(config, domains);
  return withIosPinning(config, domains, options.iosPinType ?? "ca");
};
